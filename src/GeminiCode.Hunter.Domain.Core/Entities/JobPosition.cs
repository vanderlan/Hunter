using System;

namespace GeminiCode.Hunter.Domain.Core.Entities;

public class JobPosition : BaseEntity
{
    public long JobPositionId { get; set; }
    public required string Title { get; set; }
    public required string ExternalUrl { get; set; }
    public string? Summary { get; set; }
    public string? Responsibilities { get; set; }
    public string? Requirements { get; set; }
    public string? MustHaveSkills { get; set; }
    public string? NiceToHaveSkills { get; set; }
    public bool IsActive { get; set; }
    public DateTime? ClosedAt { get; set; }
    public DateTime LastCheckedAt { get; set; }
    public string? Priority { get; set; }
    public string? CountryRestrictions { get; set; }
    public DateTime? PriorityLastSyncedAt { get; set; }

    /// <summary>
    /// Opaque, URL-safe code used to reference the position on public pages.
    /// Never expose <see cref="PublicId"/> or <see cref="JobPositionId"/> publicly.
    /// </summary>
    public string PublicCode { get; set; } = string.Empty;

    /// <summary>
    /// Company-neutral description generated by AI for the public job board.
    /// A position is only listed publicly once this content exists.
    /// </summary>
    public string? PublicSummary { get; set; }
    public string? PublicResponsibilities { get; set; }
    public string? PublicRequirements { get; set; }
    public string? PublicMustHaveSkills { get; set; }
    public string? PublicNiceToHaveSkills { get; set; }
    public DateTime? PublicContentGeneratedAt { get; set; }

    public bool IsPubliclyVisible => IsActive && !string.IsNullOrWhiteSpace(PublicSummary);
}
